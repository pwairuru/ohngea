from datetime import datetime
from typing import Optional
from uuid import UUID
from sqlmodel import Field, SQLModel
from app.db import uuid7
class CallCenterBase(SQLModel):
    domain_id: UUID = Field(foreign_key="domains.domain_id", index=True, ondelete="CASCADE")
    dialplan_uuid: Optional[UUID]=Field(default=None, foreign_key="dialplans.dialplan_uuid", index=True, ondelete="SET NULL")
    queue_name: str = Field(max_length=128)
    queue_extension: Optional[str]=Field(default=None, max_length=32)
    queue_strategy: Optional[str]=Field(default="longest-idle-agent", max_length=32)
    queue_enabled: bool = Field(default=True)
    queue_description: Optional[str]=Field(default=None, max_length=512)
    queue_greeting: Optional[str]=Field(default=None, max_length=128)
    queue_moh_sound: Optional[str]=Field(default=None, max_length=128)
    queue_record_template: Optional[str]=Field(default=None, max_length=256)
    queue_language: Optional[str]=Field(default=None, max_length=32)
    queue_dialect: Optional[str]=Field(default=None, max_length=32)
    queue_voice: Optional[str]=Field(default=None, max_length=32)
    queue_cid_prefix: Optional[str]=Field(default=None, max_length=64)
    queue_outbound_caller_id_name: Optional[str]=Field(default=None, max_length=128)
    queue_outbound_caller_id_number: Optional[str]=Field(default=None, max_length=32)
    queue_timeout_action: Optional[str]=Field(default=None, max_length=512)
    queue_max_wait_time: Optional[int]=Field(default=None)
    queue_max_wait_time_with_no_agent: Optional[int]=Field(default=None)
    queue_max_wait_time_with_no_agent_time_reached: Optional[int]=Field(default=None)
    queue_tier_rules_apply: Optional[bool]=Field(default=None)
    queue_tier_rule_wait_second: Optional[int]=Field(default=None)
    queue_tier_rule_wait_multiply_level: Optional[bool]=Field(default=None)
    queue_tier_rule_no_agent_no_wait: Optional[bool]=Field(default=None)
    queue_discard_abandoned_after: Optional[int]=Field(default=None)
    queue_abandoned_resume_allowed: Optional[bool]=Field(default=None)
    queue_announce_position: Optional[str]=Field(default=None, max_length=32)
    queue_announce_sound: Optional[str]=Field(default=None, max_length=128)
    queue_announce_frequency: Optional[int]=Field(default=None)
    queue_cc_exit_keys: Optional[str]=Field(default=None, max_length=32)
    queue_email_address: Optional[str]=Field(default=None, max_length=255)
    queue_context: Optional[str]=Field(default="public", max_length=128)
    queue_limit: Optional[str]=Field(default=None, max_length=32)
    queue_time_base_score: Optional[str]=Field(default=None, max_length=32)
    queue_time_base_score_sec: Optional[int]=Field(default=None)
class CallCenter(CallCenterBase, table=True):
    __tablename__="call_centers"
    call_center_queue_uuid: UUID = Field(default_factory=uuid7, primary_key=True)
    created_at: datetime = Field(default_factory=lambda: datetime.utcnow())
    updated_at: datetime = Field(default_factory=lambda: datetime.utcnow())
class CallCenterAgentBase(SQLModel):
    domain_id: UUID = Field(foreign_key="domains.domain_id", index=True, ondelete="CASCADE")
    call_center_queue_uuid: UUID = Field(foreign_key="call_centers.call_center_queue_uuid", index=True, ondelete="CASCADE")
    user_uuid: Optional[UUID]=Field(default=None, foreign_key="users.user_uuid", index=True, ondelete="SET NULL")
    agent_name: str = Field(max_length=128)
    agent_type: Optional[str]=Field(default="callback", max_length=32)
    agent_contact: Optional[str]=Field(default=None, max_length=128)
    agent_status: Optional[str]=Field(default="Logged Out", max_length=32)
    agent_call_timeout: Optional[int]=Field(default=None)
    agent_id: Optional[str]=Field(default=None, max_length=64)
    agent_password: Optional[str]=Field(default=None, max_length=128)
    agent_logout: Optional[str]=Field(default=None, max_length=32)
    agent_max_no_answer: Optional[int]=Field(default=None)
    agent_wrap_up_time: Optional[int]=Field(default=None)
    agent_reject_delay_time: Optional[int]=Field(default=None)
    agent_busy_delay_time: Optional[int]=Field(default=None)
    agent_no_answer_delay_time: Optional[str]=Field(default=None, max_length=64)
    agent_record: Optional[bool]=Field(default=None)
class CallCenterAgent(CallCenterAgentBase, table=True):
    __tablename__="call_center_agents"
    call_center_agent_uuid: UUID = Field(default_factory=uuid7, primary_key=True)
    created_at: datetime = Field(default_factory=lambda: datetime.utcnow())
    updated_at: datetime = Field(default_factory=lambda: datetime.utcnow())
class CallCenterTierBase(SQLModel):
    domain_id: UUID = Field(foreign_key="domains.domain_id", index=True, ondelete="CASCADE")
    call_center_queue_uuid: UUID = Field(foreign_key="call_centers.call_center_queue_uuid", index=True, ondelete="CASCADE")
    call_center_agent_uuid: UUID = Field(foreign_key="call_center_agents.call_center_agent_uuid", index=True, ondelete="CASCADE")
    agent_name: Optional[str]=Field(default=None, max_length=128)
    queue_name: Optional[str]=Field(default=None, max_length=128)
    tier_level: Optional[int]=Field(default=1)
    tier_position: Optional[int]=Field(default=1)
class CallCenterTier(CallCenterTierBase, table=True):
    __tablename__="call_center_tiers"
    call_center_tier_uuid: UUID = Field(default_factory=uuid7, primary_key=True)
    created_at: datetime = Field(default_factory=lambda: datetime.utcnow())
    updated_at: datetime = Field(default_factory=lambda: datetime.utcnow())
