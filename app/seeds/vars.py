async def seed_vars(session, domain_id) -> int:
    """Idempotent per-domain vars seed. Dedupe on (domain_id, var_name, var_category)."""
    from sqlalchemy import select as _select

    from app.vars.models import Var as _Var

    n = 0
    for v in VARS:
        r = await session.execute(
            _select(_Var).where(
                _Var.domain_id == domain_id,
                _Var.var_name == v["var_name"],
                _Var.var_category == v["var_category"],
            )
        )
        if r.scalar_one_or_none():
            continue
        session.add(
            _Var(
                domain_id=domain_id,
                var_category=v["var_category"],
                var_name=v["var_name"],
                var_value=v["var_value"],
                var_enabled=v["var_enabled"],
                var_description=v["var_description"] or None,
                var_order=v["var_order"],
                var_command=v["var_command"],
                var_hostname=v["var_hostname"],
            )
        )
        n += 1
    await session.flush()
    return n
