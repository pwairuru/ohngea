async def seed_permissions(session) -> int:
    """Idempotent global permission seed."""
    from sqlalchemy import select as _select

    from app.auth.models import Permission as _Permission
    n = 0
    for name in ALL_PERMISSIONS:
        r = await session.execute(_select(_Permission).where(_Permission.name == name))
        if r.scalar_one_or_none():
            continue
        session.add(_Permission(name=name)); n += 1
    await session.flush()
    return n
