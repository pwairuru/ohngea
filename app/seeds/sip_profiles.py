async def seed_sip_profiles(session, domain_id, domain_name: str) -> int:
    """Idempotent per-domain full sip seed (profiles + domains + settings)."""
    from sqlalchemy import select as _select

    from app.sip_profiles.models import SipProfile as _P
    from app.sip_profiles.models import SipProfileDomain as _D
    from app.sip_profiles.models import SipProfileSetting as _S

    n = 0
    for p in SIP_PROFILES:
        r = await session.execute(
            _select(_P).where(_P.domain_id == domain_id, _P.name == p["name"])
        )
        obj = r.scalar_one_or_none()
        if obj is None:
            obj = _P(
                domain_id=domain_id,
                name=p["name"],
                enabled=p["enabled"],
                sip_port=p["port"],
                description=p.get("description"),
            )
            session.add(obj)
            await session.flush()
            await session.refresh(obj)
            n += 1
        else:
            # upgrade stub rows (name+port only) to full parity on re-seed
            if not obj.description and p.get("description"):
                obj.description = p["description"]
        for d in p.get("domains", []):
            nm = (d.get("name") or "").replace("{v_sip_profile_name}", p["name"]).replace(
                "${domain_name}", domain_name
            ).replace("$${domain}", domain_name) or domain_name
            rr = await session.execute(
                _select(_D).where(_D.sip_profile_uuid == obj.sip_profile_uuid, _D.domain_name == nm)
            )
            if rr.scalar_one_or_none():
                continue
            session.add(
                _D(
                    domain_id=domain_id,
                    sip_profile_uuid=obj.sip_profile_uuid,
                    domain_name=nm,
                    domain_alias=d.get("alias") or "false",
                    domain_parse=d.get("parse") or "true",
                )
            )
            n += 1
        for s in p.get("settings", []):
            if not s.get("name"):
                continue
            rr = await session.execute(
                _select(_S).where(
                    _S.sip_profile_uuid == obj.sip_profile_uuid, _S.setting_name == s["name"]
                )
            )
            if rr.scalar_one_or_none():
                continue
            session.add(
                _S(
                    domain_id=domain_id,
                    sip_profile_uuid=obj.sip_profile_uuid,
                    setting_name=s["name"],
                    setting_value=s.get("value"),
                    enabled=True,
                )
            )
            n += 1
    await session.flush()
    return n
